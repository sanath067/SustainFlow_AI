import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages
import warnings
warnings.filterwarnings('ignore')

print("="*60)
print("GENERATING REPORT WITH GRAPHS")
print("="*60)

# Load feature importance
df = pd.read_csv('../Results/feature_importance.csv')
print(f"Loaded feature_importance.csv with {len(df)} rows")
print("Column names:", df.columns.tolist())

# Sort by importance (lowercase 'importance')
df = df.sort_values('importance', ascending=False)

# Get top features
top10 = df.head(10)
top5 = df.head(5)

# Create PDF
report_path = '../Results/guide_report.pdf'
print(f"\nGenerating: {report_path}")

with PdfPages(report_path) as pdf:
    
    # ============ PAGE 1: Summary ============
    fig1, ax1 = plt.subplots(figsize=(11, 8.5))
    ax1.axis('off')
    
    ax1.text(0.5, 0.95, 'SUSTAINFLOW AI', fontsize=22, ha='center', weight='bold')
    ax1.text(0.5, 0.90, 'Food Loss Prediction - Module 1', fontsize=16, ha='center')
    ax1.text(0.5, 0.85, 'FAO Dataset | Random Forest Model', fontsize=12, ha='center')
    
    ax1.text(0.1, 0.75, 'MODEL PERFORMANCE', fontsize=14, weight='bold')
    ax1.text(0.1, 0.69, 'R² Score: 0.655', fontsize=12)
    ax1.text(0.1, 0.65, 'RMSE: Check metrics.txt', fontsize=12)
    ax1.text(0.1, 0.61, 'MAE: Check metrics.txt', fontsize=12)
    
    ax1.text(0.1, 0.52, 'TOP 5 FEATURES', fontsize=14, weight='bold')
    for i, (idx, row) in enumerate(top5.iterrows(), 1):
        feature_name = row['feature']  # lowercase
        if len(feature_name) > 40:
            feature_name = feature_name[:37] + '...'
        ax1.text(0.1, 0.46 - i*0.06, f"{i}. {feature_name}: {row['importance']:.4f}", fontsize=11)
    
    ax1.text(0.1, 0.20, 'INPUT FEATURES', fontsize=14, weight='bold')
    ax1.text(0.1, 0.14, '• Commodity (What food item?)', fontsize=11)
    ax1.text(0.1, 0.10, '• Country (Which country?)', fontsize=11)
    ax1.text(0.1, 0.06, '• Food Supply Stage (Where in supply chain?)', fontsize=11)
    ax1.text(0.1, 0.02, '• Year (Which year?)', fontsize=11)
    
    ax1.text(0.5, 0.05, 'Generated by SustainFlow AI', fontsize=10, ha='center', style='italic')
    
    plt.tight_layout()
    pdf.savefig(fig1)
    plt.close()
    print("Page 1: Summary created")
    
    # ============ PAGE 2: BAR CHART ============
    fig2, ax2 = plt.subplots(figsize=(11, 8.5))
    
    colors = ['#4472C4' if i % 2 == 0 else '#5B9BD5' for i in range(len(top10))]
    bars = ax2.barh(top10['feature'], top10['importance'], color=colors)
    
    ax2.set_xlabel('Importance', fontsize=12)
    ax2.set_title('TOP 10 FEATURE IMPORTANCE', fontsize=14, weight='bold')
    
    for bar, val in zip(bars, top10['importance']):
        ax2.text(val + 0.001, bar.get_y() + bar.get_height()/2, f'{val:.3f}', va='center', fontsize=9)
    
    ax2.grid(axis='x', alpha=0.3)
    plt.tight_layout()
    pdf.savefig(fig2)
    plt.close()
    print("Page 2: Bar chart created")
    
    # ============ PAGE 3: PIE CHART ============
    fig3, ax3 = plt.subplots(figsize=(11, 8.5))
    
    top5_imp = top5['importance'].values
    other_imp = df['importance'][5:].sum()
    
    labels = list(top5['feature']) + ['Other Features']
    sizes = list(top5_imp) + [other_imp]
    
    # Truncate long labels
    labels = [label[:30] + '...' if len(label) > 30 else label for label in labels]
    
    colors_pie = ['#4472C4', '#5B9BD5', '#FFC000', '#70AD47', '#ED7D31', '#A5A5A5']
    explode = [0.05] * len(labels)
    
    wedges, texts, autotexts = ax3.pie(
        sizes, 
        labels=labels, 
        autopct='%1.1f%%', 
        startangle=90,
        colors=colors_pie[:len(labels)],
        explode=explode
    )
    
    for autotext in autotexts:
        autotext.set_fontsize(11)
        autotext.set_weight('bold')
    
    ax3.set_title('FEATURE IMPORTANCE DISTRIBUTION', fontsize=14, weight='bold')
    
    plt.tight_layout()
    pdf.savefig(fig3)
    plt.close()
    print("Page 3: Pie chart created")
    
    # ============ PAGE 4: COMPLETE TABLE ============
    fig4, ax4 = plt.subplots(figsize=(11, 8.5))
    ax4.axis('off')
    
    ax4.text(0.5, 0.95, 'COMPLETE FEATURE IMPORTANCE TABLE', fontsize=16, ha='center', weight='bold')
    ax4.text(0.5, 0.90, 'All features ranked by importance', fontsize=12, ha='center')
    
    table_data = []
    table_data.append(['Rank', 'Feature', 'Importance'])
    
    for i, (idx, row) in enumerate(df.iterrows(), 1):
        if i > 25:
            break
        feature_name = row['feature']
        if len(feature_name) > 40:
            feature_name = feature_name[:37] + '...'
        table_data.append([str(i), feature_name, f"{row['importance']:.4f}"])
    
    table = ax4.table(
        cellText=table_data,
        loc='center',
        cellLoc='left',
        colWidths=[0.08, 0.70, 0.15]
    )
    table.auto_set_font_size(False)
    table.set_fontsize(9)
    
    for i in range(3):
        table[(0, i)].set_facecolor('#4472C4')
        table[(0, i)].set_text_props(weight='bold', color='white')
        table[(0, i)].set_cellLoc('center')
    
    for i in range(1, len(table_data)):
        for j in range(3):
            if i % 2 == 0:
                table[(i, j)].set_facecolor('#F2F2F2')
    
    plt.tight_layout()
    pdf.savefig(fig4)
    plt.close()
    print("Page 4: Table created")
    
    # ============ PAGE 5: ACTUAL VS PREDICTED ============
    try:
        import os
        img_path = '../Results/actual_vs_predicted.png'
        if os.path.exists(img_path):
            fig5, ax5 = plt.subplots(figsize=(11, 8.5))
            ax5.axis('off')
            
            ax5.text(0.5, 0.95, 'ACTUAL VS PREDICTED', fontsize=16, ha='center', weight='bold')
            
            img = plt.imread(img_path)
            ax5.imshow(img, extent=[0.1, 0.9, 0.1, 0.8])
            
            plt.tight_layout()
            pdf.savefig(fig5)
            plt.close()
            print("Page 5: Actual vs Predicted plot added")
        else:
            print("Page 5: Skipped (actual_vs_predicted.png not found)")
    except Exception as e:
        print(f"Page 5: Skipped - {str(e)[:50]}")

print(f"\n✅ Report saved: {report_path}")
print("\nPages:")
print("   Page 1: Summary (Model info + Top Features)")
print("   Page 2: Bar Chart (Top 10 Features)")
print("   Page 3: Pie Chart (Top 5 Features Distribution)")
print("   Page 4: Complete Feature Table (Top 25)")
print("   Page 5: Actual vs Predicted Plot")
print("\n" + "="*60)
print("REPORT GENERATION COMPLETE")
print("="*60)